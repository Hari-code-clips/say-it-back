"""Audio for the synthetic set: ffmpeg for conversion and noise generation, stdlib for mixing.

Noise is generated by ffmpeg from fixed seeds (brown and pink noise, mains hum, sparse impulses),
so re-runs produce identical bytes. Mixing and level control are plain arithmetic on 16-bit PCM.
"""

import array
import io
import math
import re
import subprocess
import sys
import wave
from pathlib import Path

from config import SAMPLE_RATE, SPEECH_LOUDNESS_FILTER

PEAK_LIMIT = 29000  # about -1 dBFS; mixes are scaled down together, so the SNR is preserved


def run_ffmpeg(args: list[str]) -> None:
    proc = subprocess.run(
        ["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", *args],
        capture_output=True, text=True, check=False,
    )
    if proc.returncode != 0:
        raise RuntimeError(f"ffmpeg failed: {proc.stderr.strip()[-300:]}")


def speech_to_16k(src: Path, dst: Path) -> None:
    """TTS output (24 kHz) to 16 kHz mono 16-bit with a fixed loudness target."""
    run_ffmpeg(["-i", str(src), "-ac", "1", "-ar", str(SAMPLE_RATE), "-af", SPEECH_LOUDNESS_FILTER,
                "-c:a", "pcm_s16le", str(dst)])


def noise_bed(dst: Path, seconds: float, seed: int) -> None:
    """Site noise: brown rumble, pink mid band, 50/100/150 Hz hum and sparse decaying clicks."""
    dur = f"{seconds:.3f}"
    rate = str(SAMPLE_RATE)
    sources = [
        "-f", "lavfi", "-i", f"anoisesrc=color=brown:seed={seed}:sample_rate={rate}:duration={dur}",
        "-f", "lavfi", "-i", f"anoisesrc=color=pink:seed={seed + 1}:sample_rate={rate}:duration={dur}",
        "-f", "lavfi", "-i",
        f"aevalsrc=0.5*sin(2*PI*50*t)+0.25*sin(2*PI*100*t)+0.12*sin(2*PI*150*t):s={rate}:d={dur}",
        "-f", "lavfi", "-i",
        f"aevalsrc=exp(-300*(t-0.61*floor(t/0.61)))*sin(2*PI*1400*(t-0.61*floor(t/0.61)))"
        f"+0.7*exp(-400*(t-1.37*floor(t/1.37)))*sin(2*PI*900*(t-1.37*floor(t/1.37))):s={rate}:d={dur}",
    ]
    graph = ("[0:a]volume=1[b];[1:a]volume=0.5[p];[2:a]volume=0.3[h];[3:a]volume=0.6[i];"
             "[b][p][h][i]amix=inputs=4:normalize=0:duration=longest[o]")
    run_ffmpeg([*sources, "-filter_complex", graph, "-map", "[o]", "-ac", "1", "-ar", rate,
                "-c:a", "pcm_s16le", str(dst)])


def read_samples(path: Path) -> array.array:
    with wave.open(str(path), "rb") as wav:
        if wav.getnchannels() != 1 or wav.getsampwidth() != 2:
            raise ValueError(f"{path.name}: expected mono 16-bit PCM")
        frames = wav.readframes(wav.getnframes())
    samples = array.array("h")
    samples.frombytes(frames)
    if sys.byteorder == "big":
        samples.byteswap()
    return samples


def write_samples(path: Path, samples: array.array, rate: int = SAMPLE_RATE) -> None:
    out = array.array("h", samples)
    if sys.byteorder == "big":
        out.byteswap()
    path.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(path), "wb") as wav:
        wav.setnchannels(1)
        wav.setsampwidth(2)
        wav.setframerate(rate)
        wav.writeframes(out.tobytes())


def mean_square(samples: array.array) -> float:
    if not samples:
        return 0.0
    return sum(x * x for x in samples) / len(samples)


def mix_at_snr(speech: array.array, noise: array.array, snr_db: float) -> array.array:
    """Add noise so that mean-square speech / mean-square noise equals snr_db over the clip."""
    n = len(speech)
    if len(noise) < n:
        raise ValueError("noise bed is shorter than the speech")
    p_noise = mean_square(noise[:n])
    if p_noise == 0.0:
        raise ValueError("noise bed is silent")
    gain = math.sqrt(mean_square(speech) / (p_noise * 10 ** (snr_db / 10)))
    return _limit_peak([speech[i] + gain * noise[i] for i in range(n)])


def scale_to_dbfs(samples: array.array, dbfs: float) -> array.array:
    """Scale a signal so its RMS sits at dbfs (relative to full scale)."""
    rms = math.sqrt(mean_square(samples))
    if rms == 0.0:
        raise ValueError("cannot scale a silent signal")
    gain = 32768 * 10 ** (dbfs / 20) / rms
    return array.array("h", (_clip16(round(x * gain)) for x in samples))


def _limit_peak(values: list[float]) -> array.array:
    peak = max((abs(v) for v in values), default=0.0) or 1.0
    scale = min(1.0, PEAK_LIMIT / peak)
    return array.array("h", (_clip16(round(v * scale)) for v in values))


def _clip16(value: int) -> int:
    return max(-32768, min(32767, value))


def pcm_to_wav(data: bytes, mime_type: str) -> bytes:
    """A WAV unchanged, or raw 16-bit mono PCM (mime like 'audio/L16;codec=pcm;rate=24000') wrapped as WAV."""
    if data[:4] == b"RIFF":
        return data
    match = re.search(r"rate=(\d+)", mime_type)
    buffer = io.BytesIO()
    with wave.open(buffer, "wb") as wav:
        wav.setnchannels(1)
        wav.setsampwidth(2)
        wav.setframerate(int(match.group(1)) if match else 24000)
        wav.writeframes(data)
    return buffer.getvalue()
